from turtle import *            # подключаем модуль turtle («черепашья графика») со всеми командами
shape('turtle')                 # курсор будет выглядеть как черепашка
setup(450,350)                     # размер окна: 450 пикселей в ширину, 350 в высоту              
pensize(2)                      # толщина линии пера — 2 пикселя

def p(x, y):                    # своя функция p: перейти в точку (x, y), ничего не рисуя
    penup(); setpos(x, y)       # поднять перо (не рисовать) и переместиться в точку (x, y)
    pendown(); seth(0)          # опустить перо (снова рисовать) и повернуть черепашку вправо (на восток)

def rect(x1, y1, x2, y2):       # своя функция: закрашенный прямоугольник по двум углам
    p(x1, y1)                   # встаём в первый угол (левый верхний)
    d = abs(x2 - x1)            # ширина прямоугольника (abs — модуль, чтобы не было минуса)
    h = abs(y2 - y1)            # высота прямоугольника
    begin_fill()                # начало фигуры, которую нужно закрасить
    fd(d); rt(90)               # вперёд на ширину, поворот направо на 90° (теперь смотрим вниз)
    fd(h); rt(90)               # вниз на высоту, поворот направо (смотрим влево)
    fd(d); rt(90)               # влево на ширину, поворот направо (смотрим вверх)
    fd(h)                       # вверх на высоту — вернулись в начальную точку
    end_fill()                  # конец фигуры — прямоугольник закрашивается

#крыша                          # комментарий: дальше рисуется крыша (Python его не выполняет)
p(-200, 50)                     # встаём в левый нижний угол крыши
color('brown', 'yellow')        # цвет линии — коричневый, цвет заливки — жёлтый
begin_fill(); lt(30)            # начинаем закрашиваемую фигуру, поворот налево на 30° (вверх-вправо)
fd(200); rt(60)                 # левый скат крыши длиной 200, поворот направо на 60° (вниз-вправо)
fd(200); rt(150)                # правый скат крыши, поворот на 150° (теперь смотрим влево)
fd(346); end_fill()             # основание крыши длиной 346, треугольник закрашивается

#дом                            # комментарий: стены дома
color('brown', 'Chocolate')     # линия коричневая, заливка шоколадного цвета
rect(-200, 50, 146, -150)       # прямоугольник дома: от (-200; 50) до (146; -150), 346 × 200

#окно                           # комментарий: окно
color('blue', 'lightblue')      # линия синяя, заливка голубая
rect(-150, 0, -50, 50)          # окно шириной 100 и высотой 50 (рисуется вниз от точки (-150; 0))

#дверь                          # комментарий: дверь
color('red', 'coral')           # линия красная, заливка коралловая
rect(60, -20, 120, -150)        # дверь шириной 60 и высотой 130

done()                          # завершение: окно с рисунком остаётся открытым